/**
 * Writes `windows-link-diagnostic.ps1` — the exact PowerShell the app runs to read
 * browser address bars, extracted from the source so the two cannot drift.
 *
 * Run it on the Windows machine to see precisely what the detector sees:
 *
 *   npm run diagnose:windows
 *   powershell -NoProfile -Sta -ExecutionPolicy Bypass -File .\windows-link-diagnostic.ps1
 *
 * Output lines are the detector's own protocol:
 *   ##URL   <address bar value>  <window title>
 *   ##NOURL <window title>            address bar present but unreadable
 *   ##NOBROWSERS                      no supported browser window open
 *   ##ERR / ##WINERR                  UI Automation failed
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/main/services/link-tracker/sources/windows.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'cjs',
  external: ['electron'],
  logLevel: 'error',
});

const code = result.outputFiles[0].text;
const module = { exports: {} };
new Function('module', 'exports', 'require', code)(module, module.exports, () => ({}));

const script = module.exports.ADDRESS_BAR_SCRIPT;
if (typeof script !== 'string' || !script.includes('UIAutomationClient')) {
  console.error('[diagnose] could not extract the address-bar script');
  process.exit(1);
}

const out = resolve(root, 'windows-link-diagnostic.ps1');
writeFileSync(out, `# Generated by scripts/emit-windows-diagnostic.mjs — do not edit.\r\n${script.replace(/\n/g, '\r\n')}`, 'utf8');
console.log(`[diagnose] wrote ${out}`);
console.log('[diagnose] run it on Windows with:');
console.log('  powershell -NoProfile -Sta -ExecutionPolicy Bypass -File .\\windows-link-diagnostic.ps1');
